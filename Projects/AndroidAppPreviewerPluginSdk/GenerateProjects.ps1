param([switch]$Check, [switch]$PassThru)

$ErrorActionPreference = 'Stop'
$root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../..'))
$component = Get-Content (Join-Path $PSScriptRoot 'Files.json') -Raw | ConvertFrom-Json
$delivery = Get-Content (Join-Path $root 'Packages/Windows/AndroidAppPreviewerPluginSdk/Delivery/NuGet/Delivery.json') -Raw | ConvertFrom-Json
$prefix = 'Projects/AndroidAppPreviewerPluginSdk/'
$sharedGuid = '{EE5E5C89-064F-2626-8262-C411FFA6BCF3}'
$items = [Collections.Generic.List[object]]::new()
$seen = @{}

# Files.json остаётся общим списком для MSBuild, CMake и поставки исходников.
foreach ($group in @(@{ Type = 'ClInclude'; Files = $component.headers }, @{ Type = 'ClCompile'; Files = $component.sources })) {
    foreach ($file in $group.Files) {
        if (-not $file.StartsWith($prefix, [StringComparison]::Ordinal) -or $file -match '\.\.|[\\:*?]' -or -not (Test-Path -LiteralPath (Join-Path $root $file) -PathType Leaf)) {
            throw "Invalid component file: $file"
        }
        if ($seen.ContainsKey($file)) {
            throw "Duplicate component file: $file"
        }
        $seen[$file] = $true
        $relative = $file.Substring($prefix.Length).Replace('/', '\')
        $filter = [IO.Path]::GetDirectoryName($relative)
        $items.Add(@{ Type = $group.Type; Path = '$(MSBuildThisFileDirectory)' + $relative; Filter = $filter })
    }
}
foreach ($file in @('Files.json', 'CMakeLists.txt', 'GenerateProjects.ps1')) {
    $items.Add(@{ Type = 'None'; Path = '$(MSBuildThisFileDirectory)' + $file; Filter = '' })
}

function Escape-ProjectXml([string]$Value) {
    return [Security.SecurityElement]::Escape($Value)
}

$shared = [Collections.Generic.List[string]]::new()
$shared.Add('<?xml version="1.0" encoding="utf-8"?>')
$shared.Add('<!-- Generated by GenerateProjects.ps1. Edit Files.json and Delivery/NuGet/Delivery.json. -->')
$shared.Add('<Project xmlns="http://schemas.microsoft.com/developer/msbuild/2003">')
$shared.Add('  <PropertyGroup Label="Globals">')
$shared.Add('    <HasSharedItems>true</HasSharedItems>')
$shared.Add("    <ItemsProjectGuid>$sharedGuid</ItemsProjectGuid>")
$shared.Add('  </PropertyGroup>')
$shared.Add('  <Import Project="$(MSBuildThisFileDirectory)AndroidAppPreviewerPluginSdk.Dependencies.props" />')
$shared.Add('  <ItemDefinitionGroup>')
$shared.Add('    <ClCompile>')
$shared.Add('      <AdditionalIncludeDirectories>$(MSBuildThisFileDirectory)..;$(MSBuildThisFileDirectory);$(PkgUniversalDevKit_OpenGLESRenderer)\include\ANGLE;%(AdditionalIncludeDirectories)</AdditionalIncludeDirectories>')
$shared.Add('      <PreprocessorDefinitions>NOMINMAX;WIN32_LEAN_AND_MEAN;%(PreprocessorDefinitions)</PreprocessorDefinitions>')
$shared.Add('      <LanguageStandard>stdcpp20</LanguageStandard>')
$shared.Add('      <ExceptionHandling>Sync</ExceptionHandling>')
$shared.Add('      <PrecompiledHeader>NotUsing</PrecompiledHeader>')
$shared.Add('      <AdditionalOptions>/utf-8 %(AdditionalOptions)</AdditionalOptions>')
$shared.Add('    </ClCompile>')
$shared.Add('  </ItemDefinitionGroup>')
$shared.Add('  <ItemGroup>')
foreach ($item in $items) {
    $shared.Add('    <' + $item.Type + ' Include="' + (Escape-ProjectXml $item.Path) + '" />')
}
$shared.Add('  </ItemGroup>')
$shared.Add('</Project>')

# Версии зависимостей берутся из существующего описания NuGet-доставки SDK.
$dependencies = [Collections.Generic.List[string]]::new()
$dependencies.Add('<?xml version="1.0" encoding="utf-8"?>')
$dependencies.Add('<!-- Generated by GenerateProjects.ps1. Edit Delivery/NuGet/Delivery.json. -->')
$dependencies.Add('<Project xmlns="http://schemas.microsoft.com/developer/msbuild/2003">')
$dependencies.Add('  <ItemGroup>')
foreach ($dependency in $delivery.dependencies) {
    $dependencies.Add('    <PackageReference Include="' + (Escape-ProjectXml $dependency.id) + '" Version="[' + (Escape-ProjectXml $dependency.version) + ']" GeneratePathProperty="true" />')
}
$dependencies.Add('  </ItemGroup>')
$dependencies.Add('</Project>')

$filters = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
foreach ($item in $items) {
    $filter = $item.Filter
    while ($filter) {
        [void]$filters.Add($filter)
        $filter = [IO.Path]::GetDirectoryName($filter)
    }
}
$filterLines = [Collections.Generic.List[string]]::new()
$filterLines.Add('<?xml version="1.0" encoding="utf-8"?>')
$filterLines.Add('<!-- Generated by GenerateProjects.ps1. Edit Files.json. -->')
$filterLines.Add('<Project xmlns="http://schemas.microsoft.com/developer/msbuild/2003">')
$filterLines.Add('  <ItemGroup>')
foreach ($filter in ($filters | Sort-Object)) {
    $filterLines.Add('    <Filter Include="' + (Escape-ProjectXml $filter) + '" />')
}
$filterLines.Add('  </ItemGroup>')
$filterLines.Add('  <ItemGroup>')
foreach ($item in $items) {
    $opening = '    <' + $item.Type + ' Include="' + (Escape-ProjectXml $item.Path) + '"'
    if ($item.Filter) {
        $filterLines.Add($opening + '>')
        $filterLines.Add('      <Filter>' + (Escape-ProjectXml $item.Filter) + '</Filter>')
        $filterLines.Add('    </' + $item.Type + '>')
    } else {
        $filterLines.Add($opening + ' />')
    }
}
$filterLines.Add('  </ItemGroup>')
$filterLines.Add('</Project>')

$outputs = [ordered]@{
    'AndroidAppPreviewerPluginSdk.Shared.vcxitems' = $shared -join "`n"
    'AndroidAppPreviewerPluginSdk.Shared.vcxitems.filters' = $filterLines -join "`n"
    'AndroidAppPreviewerPluginSdk.Static.vcxproj.filters' = $filterLines -join "`n"
    'AndroidAppPreviewerPluginSdk.Dependencies.props' = $dependencies -join "`n"
}
$updates = @()
foreach ($name in $outputs.Keys) {
    $path = Join-Path $PSScriptRoot $name
    $original = if (Test-Path -LiteralPath $path) { [IO.File]::ReadAllText($path).Replace("`r`n", "`n") } else { $null }
    if ($original -cne $outputs[$name]) {
        $updates += [pscustomobject]@{ Path = $path; Content = $outputs[$name]; Original = $original }
    }
}
if ($PassThru) {
    return $updates
}
if ($Check) {
    if ($updates.Count) {
        throw 'Native SDK projects are out of date. Run GenerateProjects.ps1.'
    }
    Write-Host 'Native SDK projects are up to date.'
    return
}
foreach ($update in $updates) {
    [IO.File]::WriteAllText($update.Path, $update.Content, [Text.UTF8Encoding]::new($false))
    Write-Host "Updated: $($update.Path)"
}